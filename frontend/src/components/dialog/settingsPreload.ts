import PlaceholderIcon from "phosphor-svelte/lib/PlaceholderIcon";
import type { Component } from "svelte";
import { parseMarkdown } from "@/lib/utils/markdown";

/** Props of a subpage that reads the shared context of the dialog. */
export type SubpageProps<TContext> = { context: () => TContext };

/** A component that takes no props at all, e.g. one that never calls `$props()`. */
export type PropsFreeComponent = Component<Record<string, never>>;

/** A page that renders a component receiving the dialog context as its `context` prop. */
type ComponentPage<TContext> = {
    type: "component";
    component: Component<SubpageProps<TContext>>;
};

/** A page that renders a component taking no props. */
type StaticPage = {
    type: "static";
    component: PropsFreeComponent;
};

/** What a caller passes to {@link preload} for one page. */
type PageTemplate<TContext> =
    | {
          /** Represents a Markdown document. */
          type: "markdown";
          /**
           * `text` must be valid GFM (GitHub-Flavored Markdown).
           * Security note: the compiled HTML is sanitized when rendered, so
           * unsupported or potentially unsafe HTML may be removed.
           */
          text: string;
      }
    | ComponentPage<TContext>
    | StaticPage;

/** One entry passed to {@link preload}: the page template plus how its tab looks. */
type PreloadTemplate<TContext> = PageTemplate<TContext> & {
    icon?: Component;
    label?: string;
};

/** A preloaded page. {@link preload} builds them and `SettingsDialog` renders them. */
export type Page<TContext> =
    | {
          type: "markdown";
          /** The Markdown source compiled to HTML. It is sanitized when rendered. */
          html: string;
      }
    | ComponentPage<TContext>
    | StaticPage;

/** A tab of the dialog sidebar. */
export type Tab = {
    /** A random string generated by `crypto.randomUUID()`. It is the key of the tab's page in the page map. */
    id: string;
    /** The name of the tab. */
    label: string;
    /** The tab's icon. */
    icon: Component;
};

/**
 * Preloads the data required by SettingsDialog for rendering.
 * This function must be invoked at module scope.
 *
 * The returned value is the `preloaded` dataset that is passed to `SettingsDialog`.
 * Callers rarely need to read it. One exception is choosing the initial tab, as in
 * `let activeId = $state(preloaded.tabList[0]?.id ?? "");`.
 */
export function preload<TContext = unknown>(templates: PreloadTemplate<TContext>[]) {
    const tabList: Tab[] = [];

    const pageMap: Record<string, Page<TContext>> = {};

    for (const template of templates) {
        const id = crypto.randomUUID();

        if (template.type === "markdown") {
            pageMap[id] = { type: "markdown", html: parseMarkdown(template.text) };
        } else if (template.type === "component") {
            pageMap[id] = { type: "component", component: template.component };
        } else if (template.type === "static") {
            pageMap[id] = { type: "static", component: template.component };
        } else {
            template satisfies never;
        }

        tabList.push({
            id,
            label: template.label ?? "Untitled",
            icon: template.icon ?? PlaceholderIcon,
        });
    }

    return { tabList, pageMap };
}
